"""Pre-loaded per-venue reference data: named corners and pit lanes.

The data files in ``data/`` are generated by ``scripts/build_track_refs.py`` from
OpenStreetMap (ODbL 1.0, (c) OpenStreetMap contributors) and hold real-world
coordinates only. Nothing here is per-session: a session is matched to a venue by
the track position iRacing writes into ``WeekendInfo``, and a point on the lap is
named by its distance to the mapped corner polylines. A venue with no mapped name
for a corner leaves it unnamed rather than guessing.
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass, field
from functools import cache
from importlib import resources
from typing import Any

import numpy as np

#: Metres per degree of latitude (WGS84 mean), for a local flat projection.
_M_PER_DEG_LAT = 111_132.0
#: How far a telemetry point may sit from a mapped centreline and still be "on" it:
#: half a track width plus the offset between iRacing's scan and the OSM trace.
MATCH_RADIUS_M = 30.0
#: A session whose header position is this close to a venue belongs to it.
VENUE_RADIUS_M = 5_000.0


@dataclass(frozen=True)
class Segment:
    """One named stretch of circuit (a corner or a named straight) from OSM."""

    name: str
    kind: str  # "corner" | "straight"
    polylines: tuple[tuple[tuple[float, float], ...], ...]
    osm_ways: tuple[int, ...] = ()
    osm_nodes: tuple[int, ...] = ()
    ref: str | None = None
    length_m: float | None = None
    #: Match radius when the corner is mapped as a labelled point, not a centreline.
    radius_m: float | None = None


@dataclass(frozen=True)
class TrackReference:
    """Reference data for one venue, covering every layout iRacing runs there."""

    key: str
    name: str
    country: str
    center: tuple[float, float]
    bbox: tuple[float, float, float, float]
    iracing_names: tuple[str, ...]
    segments: tuple[Segment, ...]
    pit_lanes: tuple[tuple[tuple[float, float], ...], ...] = ()
    attribution: str = ""
    _projected: dict[str, Any] = field(default_factory=dict, compare=False, repr=False)

    @property
    def corners(self) -> tuple[Segment, ...]:
        return tuple(s for s in self.segments if s.kind == "corner")

    def summary(self) -> dict[str, Any]:
        return {
            "key": self.key,
            "name": self.name,
            "country": self.country,
            "center": list(self.center),
            "iracing_names": list(self.iracing_names),
            "named_corners": len(self.corners),
            "named_straights": len(self.segments) - len(self.corners),
            "has_pit_lane": bool(self.pit_lanes),
            "attribution": self.attribution,
        }

    def detail(self) -> dict[str, Any]:
        out = self.summary()
        out["segments"] = [
            {
                "name": s.name,
                "kind": s.kind,
                "ref": s.ref,
                "length_m": s.length_m,
                "osm_ways": list(s.osm_ways),
                "osm_nodes": list(s.osm_nodes),
                "radius_m": s.radius_m,
                "polylines": [[list(p) for p in line] for line in s.polylines],
            }
            for s in self.segments
        ]
        out["pit_lanes"] = [[list(p) for p in line] for line in self.pit_lanes]
        return out

    # ------------------------------------------------------------------ geometry
    def _xy(self, lat, lon) -> tuple[np.ndarray, np.ndarray]:
        lat0, lon0 = self.center
        x = (np.asarray(lon, dtype=float) - lon0) * _M_PER_DEG_LAT * math.cos(math.radians(lat0))
        y = (np.asarray(lat, dtype=float) - lat0) * _M_PER_DEG_LAT
        return x, y

    def _segment_edges(self) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Every polyline edge as (start xy, end xy, owning segment index, slack m).

        A point-mapped corner is one zero-length edge; its slack is how much further
        than :data:`MATCH_RADIUS_M` a trace point may be and still count.
        """
        if "edges" not in self._projected:
            a, b, owner, slack = [], [], [], []
            for si, seg in enumerate(self.segments):
                extra = max(0.0, (seg.radius_m or MATCH_RADIUS_M) - MATCH_RADIUS_M)
                for line in seg.polylines:
                    pts = np.array(line, dtype=float)
                    x, y = self._xy(pts[:, 0], pts[:, 1])
                    xy = np.column_stack([x, y])
                    if len(xy) == 1:
                        xy = np.vstack([xy, xy])
                    a.append(xy[:-1])
                    b.append(xy[1:])
                    owner.append(np.full(len(xy) - 1, si))
                    slack.append(np.full(len(xy) - 1, extra))
            if a:
                self._projected["edges"] = (
                    np.vstack(a), np.vstack(b), np.concatenate(owner), np.concatenate(slack)
                )
            else:
                empty = np.zeros((0, 2))
                self._projected["edges"] = (empty, empty, np.zeros(0, dtype=int), np.zeros(0))
        return self._projected["edges"]

    def nearest_segments(
        self, lat, lon, *, kinds: tuple[str, ...] = ("corner", "straight")
    ) -> tuple[np.ndarray, np.ndarray]:
        """For each point, the index of the nearest segment of ``kinds`` and its distance (m).

        The distance is less any point-label slack, so it compares against
        :data:`MATCH_RADIUS_M` for every segment. Index is -1 where no segment of
        those kinds exists.
        """
        x, y = self._xy(np.atleast_1d(lat), np.atleast_1d(lon))
        p = np.column_stack([x, y])
        a, b, owner, slack = self._segment_edges()
        keep = np.isin(owner, [i for i, s in enumerate(self.segments) if s.kind in kinds])
        a, b, owner, slack = a[keep], b[keep], owner[keep], slack[keep]
        if owner.size == 0:
            return np.full(len(p), -1), np.full(len(p), np.inf)
        ab = b - a
        denom = np.maximum((ab**2).sum(axis=1), 1e-9)
        best_d = np.full(len(p), np.inf)
        best_i = np.full(len(p), -1)
        for start in range(0, len(p), 2048):  # bounded memory on long laps
            chunk = p[start : start + 2048]
            ap = chunk[:, None, :] - a[None, :, :]
            t = np.clip((ap * ab[None, :, :]).sum(axis=2) / denom[None, :], 0.0, 1.0)
            proj = a[None, :, :] + t[:, :, None] * ab[None, :, :]
            d = np.sqrt(((chunk[:, None, :] - proj) ** 2).sum(axis=2)) - slack[None, :]
            j = d.argmin(axis=1)
            best_d[start : start + len(chunk)] = d[np.arange(len(chunk)), j]
            best_i[start : start + len(chunk)] = owner[j]
        return best_i, best_d

    def name_at(
        self, lat: float, lon: float, *, max_m: float = MATCH_RADIUS_M
    ) -> Segment | None:
        """The named corner at a real-world position, or ``None`` if none is mapped there."""
        idx, dist = self.nearest_segments([lat], [lon], kinds=("corner",))
        if idx[0] < 0 or dist[0] > max_m:
            return None
        return self.segments[int(idx[0])]

    def distance_to_m(self, lat: float, lon: float) -> float:
        x, y = self._xy(lat, lon)
        return float(math.hypot(float(x), float(y)))


def _parse(data: dict[str, Any]) -> TrackReference:
    segments = tuple(
        Segment(
            name=s["name"],
            kind=s.get("kind", "corner"),
            polylines=tuple(tuple((float(p[0]), float(p[1])) for p in line)
                            for line in s["polylines"]),
            osm_ways=tuple(s.get("osm_ways", ())),
            osm_nodes=tuple(s.get("osm_nodes", ())),
            ref=s.get("ref"),
            length_m=s.get("length_m"),
            radius_m=s.get("radius_m"),
        )
        for s in data.get("segments", ())
    )
    return TrackReference(
        key=data["key"],
        name=data["name"],
        country=data.get("country", ""),
        center=(float(data["center"][0]), float(data["center"][1])),
        bbox=tuple(float(v) for v in data["bbox"]),  # type: ignore[arg-type]
        iracing_names=tuple(n.lower() for n in data.get("iracing_names", ())),
        segments=segments,
        pit_lanes=tuple(tuple((float(p[0]), float(p[1])) for p in pl["points"])
                        for pl in data.get("pit_lanes", ())),
        attribution=data.get("attribution", ""),
    )


@cache
def load_all() -> dict[str, TrackReference]:
    """Every pre-loaded venue, keyed by venue key (``spa``, ``monza``...)."""
    out: dict[str, TrackReference] = {}
    root = resources.files("rtv.tracks").joinpath("data")
    for entry in sorted(root.iterdir(), key=lambda p: p.name):
        if entry.name.endswith(".json"):
            ref = _parse(json.loads(entry.read_text(encoding="utf-8")))
            out[ref.key] = ref
    return out


def get(key: str) -> TrackReference | None:
    return load_all().get(key)


def _header_float(raw: Any) -> float | None:
    """``"50.444061 m"`` (iRacing writes a unit even on degrees) -> 50.444061."""
    if raw is None:
        return None
    try:
        return float(str(raw).split()[0])
    except (ValueError, IndexError):
        return None


def resolve(weekend: dict[str, Any] | None) -> TrackReference | None:
    """Match a session's ``WeekendInfo`` to a pre-loaded venue.

    Position first (``TrackLatitude``/``TrackLongitude`` within a few km of the
    venue), since it does not depend on how iRacing spells the track; the
    ``TrackName`` prefix is the fallback for headers without a position.
    """
    if not weekend:
        return None
    refs = load_all()
    lat = _header_float(weekend.get("TrackLatitude"))
    lon = _header_float(weekend.get("TrackLongitude"))
    if lat is not None and lon is not None and (lat, lon) != (0.0, 0.0):
        best = min(refs.values(), key=lambda r: r.distance_to_m(lat, lon), default=None)
        if best is not None and best.distance_to_m(lat, lon) <= VENUE_RADIUS_M:
            return best
    name = str(weekend.get("TrackName") or "").lower().replace("_", " ")
    for ref in refs.values():
        if any(name.startswith(prefix) for prefix in ref.iracing_names):
            return ref
    return None
